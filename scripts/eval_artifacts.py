#!/usr/bin/env python3
"""Plot results table/curves and run top-1 smoke detection on sample images."""
from __future__ import annotations

import argparse
import random
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[1]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

import cv2
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from smoke_pipeline.composite import build_composite, composite_xyxy_to_original, nms_numpy
from smoke_pipeline.viz import draw_detection


def plot_curves(csv_path: Path, out_path: Path) -> None:
    df = pd.read_csv(csv_path)
    df.columns = [c.strip() for c in df.columns]
    fig, axes = plt.subplots(2, 3, figsize=(14, 8))
    plots = [
        ("train/box_loss", "train/cls_loss", "train/dfl_loss"),
        ("metrics/precision(B)", "metrics/recall(B)", "metrics/mAP50(B)"),
    ]
    for ax_row, row_keys in zip(axes, plots):
        for ax, key in zip(ax_row, row_keys):
            if key in df.columns:
                ax.plot(df["epoch"], df[key], marker="o", markersize=3)
            ax.set_title(key)
            ax.set_xlabel("epoch")
            ax.grid(True, alpha=0.3)
    fig.suptitle("smoke_half_50ep training metrics", fontsize=12)
    fig.tight_layout()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=150)
    plt.close(fig)


def _metrics_frame(df: pd.DataFrame) -> pd.DataFrame:
    cols = [
        "epoch",
        "metrics/precision(B)",
        "metrics/recall(B)",
        "metrics/mAP50(B)",
        "metrics/mAP50-95(B)",
        "train/box_loss",
        "val/box_loss",
    ]
    cols = [c for c in cols if c in df.columns]
    slim = df[cols].copy()
    slim.columns = [
        "Epoch",
        "Precision",
        "Recall",
        "mAP50",
        "mAP50-95",
        "Train box loss",
        "Val box loss",
    ]
    return slim


def write_results_table_latex(best: pd.Series, out_tex: Path, run_epochs: int) -> None:
    tex = (
        "% Auto-generated by scripts/eval_artifacts.py (best epoch by mAP50)\n"
        "\\begin{table}[ht]\n"
        "\\centering\n"
        "\\caption{Best validation metrics for smoke detection "
        f"(50\\% smoke-only subset, {run_epochs} epochs, epoch {int(best['Epoch'])}).}}\n"
        "\\label{tab:smoke_half_50ep}\n"
        "\\begin{tabular}{rrrrrrr}\n"
        "\\toprule\n"
        "Epoch & Precision & Recall & mAP$_{50}$ & mAP$_{50:95}$ "
        "& Train box loss & Val box loss \\\\\n"
        "\\midrule\n"
        f"{int(best['Epoch'])} & {best['Precision']:.4f} & {best['Recall']:.4f} & "
        f"{best['mAP50']:.4f} & {best['mAP50-95']:.4f} & "
        f"{best['Train box loss']:.3f} & {best['Val box loss']:.3f} \\\\\n"
        "\\bottomrule\n"
        "\\end{tabular}\n"
        "\\end{table}\n"
    )
    out_tex.write_text(tex, encoding="utf-8")


def write_results_table(
    csv_path: Path, out_md: Path, out_csv: Path, out_tex: Path
) -> pd.DataFrame:
    df = pd.read_csv(csv_path)
    df.columns = [c.strip() for c in df.columns]
    slim = _metrics_frame(df)
    best_idx = df["metrics/mAP50(B)"].idxmax()
    best = slim.loc[best_idx]
    best_epoch = int(best["Epoch"])
    best_map = float(best["mAP50"])
    run_epochs = int(df["epoch"].max())

    out_md.parent.mkdir(parents=True, exist_ok=True)
    best_fmt = best.to_frame().T.copy()
    for c in ["Precision", "Recall", "mAP50", "mAP50-95"]:
        best_fmt[c] = best_fmt[c].map(lambda x: f"{x:.4f}")
    for c in ["Train box loss", "Val box loss"]:
        best_fmt[c] = best_fmt[c].map(lambda x: f"{x:.3f}")
    best_fmt["Epoch"] = best_fmt["Epoch"].astype(int)

    out_md.write_text(
        "# smoke_half_50ep — best results (by mAP50)\n\n"
        + best_fmt.to_markdown(index=False)
        + f"\n\nSelected epoch **{best_epoch}** of **{run_epochs}** (highest mAP50 = {best_map:.4f}).\n",
        encoding="utf-8",
    )
    best.to_frame().T.to_csv(out_csv, index=False)
    write_results_table_latex(best, out_tex, run_epochs)
    return df


def resolve_image_dir(
    image_dir: Path | None,
    report_dir: Path,
    fasdd_root: Path,
    n_samples: int,
    seed: int,
) -> Path | None:
    """Pick a folder of original frames for sample inference."""
    candidates: list[Path] = []
    if image_dir is not None:
        candidates.append(image_dir.expanduser().resolve())
    candidates.extend(
        [
            _ROOT / "data/fasdd_smoke_half/images/val",
            report_dir / "sample_images",
            _ROOT / "data/fasdd_smoke_0p1pct/images/val",
        ]
    )
    for c in candidates:
        if c.is_dir() and (list(c.glob("*.jpg")) or list(c.glob("*.png"))):
            return c

    val_list = fasdd_root / "annotations/YOLO_UAV/val.txt"
    img_root = fasdd_root / "images"
    if not val_list.is_file() or not img_root.is_dir():
        return None

    lines = [ln.strip() for ln in val_list.read_text(encoding="utf-8").splitlines() if ln.strip()]
    rng = random.Random(seed)
    picked = rng.sample(lines, k=min(n_samples * 3, len(lines)))
    staging = report_dir / "sample_images"
    staging.mkdir(parents=True, exist_ok=True)
    n = 0
    for line in picked:
        rel = line.strip().lstrip("./").replace("\\", "/")
        src = fasdd_root / rel
        if not src.is_file():
            src = img_root / Path(rel).name
        if src.is_file():
            dst = staging / src.name
            if not dst.exists():
                dst.write_bytes(src.read_bytes())
            n += 1
        if n >= n_samples:
            break
    return staging if n else None


def eval_random_images(
    weights: Path,
    image_dir: Path,
    out_dir: Path,
    n: int,
    seed: int,
    conf: float,
    imgsz: int,
) -> None:
    from ultralytics import YOLO

    paths = sorted(image_dir.glob("*.jpg")) + sorted(image_dir.glob("*.png"))
    if not paths:
        raise SystemExit(f"No images in {image_dir}")
    rng = random.Random(seed)
    picked = rng.sample(paths, k=min(n, len(paths)))
    model = YOLO(str(weights))
    names = model.names
    out_dir.mkdir(parents=True, exist_ok=True)

    for im_path in picked:
        bgr = cv2.imread(str(im_path))
        if bgr is None:
            continue
        comp, meta = build_composite(bgr, out_size=imgsz)
        res = model.predict(source=comp, imgsz=imgsz, conf=conf, verbose=False)[0]
        panel = bgr.copy()
        if res.boxes is not None and len(res.boxes):
            xyxy = res.boxes.xyxy.cpu().numpy()
            scores = res.boxes.conf.cpu().numpy()
            cls = res.boxes.cls.cpu().numpy().astype(int)
            mapped = np.stack([composite_xyxy_to_original(b, meta) for b in xyxy], axis=0)
            keep = nms_numpy(mapped, scores, iou_thresh=0.55)
            if keep:
                best_i = keep[int(scores[keep].argmax())]
                draw_detection(
                    panel,
                    mapped[best_i],
                    int(cls[best_i]),
                    float(scores[best_i]),
                    names,
                )
            else:
                cv2.putText(panel, "no detection", (12, 28), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (0, 0, 255), 2)
        else:
            cv2.putText(panel, "no detection", (12, 28), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (0, 0, 255), 2)
        cv2.imwrite(str(out_dir / im_path.name), panel)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--artifacts", type=Path, default=Path("artifacts/smoke_half_50ep"))
    ap.add_argument(
        "--image-dir",
        type=Path,
        default=None,
        help="Original images/val (not composite). If missing, uses FASDD_UAV val.txt samples.",
    )
    ap.add_argument(
        "--fasdd-root",
        type=Path,
        default=Path("data/FASDD_UAV"),
        help="Used to sample val images when --image-dir is absent",
    )
    ap.add_argument("--n-samples", type=int, default=8)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--conf", type=float, default=0.12)
    ap.add_argument("--imgsz", type=int, default=640)
    ap.add_argument("--skip-samples", action="store_true", help="Only write tables and curves")
    args = ap.parse_args()

    art = args.artifacts.expanduser().resolve()
    csv_path = art / "results.csv"
    if not csv_path.is_file():
        raise SystemExit(f"Missing {csv_path}")

    report_dir = art / "report"
    write_results_table(
        csv_path,
        report_dir / "results_table.md",
        report_dir / "results_table.csv",
        report_dir / "results_table.tex",
    )
    plot_curves(csv_path, report_dir / "results_curves.png")

    if not args.skip_samples:
        img_dir = resolve_image_dir(
            args.image_dir,
            report_dir,
            args.fasdd_root.expanduser().resolve(),
            args.n_samples,
            args.seed,
        )
        if img_dir is None:
            print(
                "skip sample predictions: no images found.\n"
                "  Prepare data/fasdd_smoke_half locally, or keep data/FASDD_UAV unpacked, or pass --image-dir."
            )
        else:
            print(f"sample images from: {img_dir}")
            eval_random_images(
                art / "best.pt",
                img_dir,
                report_dir / "sample_predictions",
                args.n_samples,
                args.seed,
                args.conf,
                args.imgsz,
            )

    print(f"wrote {report_dir}/")
    print("  results_table.md, results_table.csv, results_table.tex")
    print("  results_curves.png")
    if not args.skip_samples:
        print("  sample_predictions/*.jpg (if images were available)")


if __name__ == "__main__":
    main()
